"""GraphScene, a generic flow-graph navigation library.

It exposes loading a declared flow graph into its typed model (`load_graph`, `load_graph_file`,
`FlowGraph` and the objects it holds), and `GraphError`, the error every rejection raises.
Alongside loading, it exposes the static checker, `static_violations`, and the walker, `Walker`,
which steps a loaded graph and saves its position through a `StateStore` such as the file-backed
`FileStateStore`. It declares how a node is run, the executor protocol `Executor` with its
`NodeResult`, and ships the built-in `StubExecutor` and `return_violations`. It exposes the
execution rules: `execute_set`, which runs one dispatch set through a caller's `Executor` under the
per-set safety contract `clear_set`, the per-node attempt rule `AttemptBook` and the
`UndeliveredBreaker`, with the types they compute over, the host-supplied `ExecutionLimits` and
the `RunSignals`, `DispatchCounter` and `LaunchSink` protocols the host implements. Run mode,
`start_run` and `continue_run`, drives a walk end to end through a caller's `Executor`, applying
`execute_set` set by set and returning a `RunExit`, while step mode, `Walker`, stays the
synchronous route. Run mode runs the hooks a graph names through a caller's `HookHost`, each with
its `HookCall`. The surface is re-exported from `graphscene.facade`; no module inside the package
imports from the package root.

The boundary: this package imports only the standard library, itself and its declared runtime
dependencies, and it never reads the harness's configuration file. Harness integration lives in a
separate distribution that depends on this one, never the reverse (`tests/test_boundary.py`).
"""

